//! MCP server exposing the TypR compiler to AI agents.
//!
//! Runs over stdio (wired as the `typr mcp` subcommand — never an
//! `npx`/`sh -c` one-liner, see the crate-level design notes) and offers
//! `check` (type-check only) and `build` (transpile to R) tools, both
//! in-process: no filesystem, no project directory, no `.typr_cache`. They
//! reuse the same inlined-context recipe as `typr-wasm`'s `compile`/
//! `typeCheck` (the browser playground), which is the proof this works
//! without I/O.
//!
//! It also serves read-only **resources**, kept in-process the same way
//! `STD_R` is: a vendored snapshot (`data/*.md`, `include_str!`'d below), not
//! a live fetch from the docs site. **These snapshots must be refreshed by
//! hand** (`cp` from `typr.github.io/docs/...`) whenever the source page
//! changes — there is no CI check tying the two repos together yet.
//!
//! `typr://lexicon` and `typr://operators` are the generated reference
//! tables published at `typr.github.io/docs/reference/{lexicon,operators}.md`
//! (themselves regenerated there by `npm run syntax:reference`), so an agent
//! that hits an unfamiliar sigil or operator in a `check`/`build` diagnostic
//! (say `?B` or `|>`) can look it up without leaving the MCP session or
//! guessing.
//!
//! `typr://pitfalls`, `typr://escape-hatches` and `typr://cheatsheet` are
//! aimed the other direction: not "what does this diagnostic mean" but "how
//! do I write this idiomatically" — known parser gotchas
//! (`docs/concepts/known-pitfalls.md`), the sanctioned ways to drop out of
//! the type system (`docs/reference/escape-hatches.md`), and a side-by-side
//! R/TypR comparison (`docs/reference/cheatsheet.md`).
//!
//! A third tool, `explain`, takes a diagnostic `code` (`T0xx`/`S0xx`, as
//! returned by `check`/`build`) and returns a longer explanation plus a
//! minimal before/after example, for every code in [`explain::ENTRIES`] —
//! see that module's docs for the handful of declared-but-dead codes it
//! doesn't (and can't) cover.
//!
//! Type checking is recursive, so a long-lived server must drive it from a
//! large-stack thread — see [`run_stdio`].
//!
//! ## Client configuration
//!
//! Point an MCP client at the `typr` binary with the `mcp` argument. After
//! `cargo install typr`, that's just:
//!
//! ```json
//! {
//!   "mcpServers": {
//!     "typr": {
//!       "command": "typr",
//!       "args": ["mcp"]
//!     }
//!   }
//! }
//! ```
//!
//! Building from a local checkout instead? Point `command` at
//! `target/debug/typr` (or `target/release/typr`).

