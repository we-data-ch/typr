fn read_syntax_resource(uri: &str) -> Result<ReadResourceResult, McpError> {
    let text = match uri {
        LEXICON_URI => LEXICON_MD,
        OPERATORS_URI => OPERATORS_MD,
        STDLIB_URI => STDLIB_MD,
        PITFALLS_URI => PITFALLS_MD,
        ESCAPE_HATCHES_URI => ESCAPE_HATCHES_MD,
        CHEATSHEET_URI => CHEATSHEET_MD,
        DOCS_INDEX_URI => DOCS_INDEX_MD,
        _ => {
            return Err(McpError::invalid_params(format!("unknown resource uri: {uri}"), None));
        }
    };
    Ok(ReadResourceResult::new(vec![
        ResourceContents::text(text, uri).with_mime_type("text/markdown")
    ]))
}

#[derive(Debug, Deserialize, JsonSchema)]
pub struct CheckParams {
    /// TypR source code to type-check.
    pub source: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct Diagnostic {
    /// Stable error code (`T0xx` for type errors, `S0xx` for syntax errors) —
    /// see `TypeError::code`/`SyntaxError::code` in typr-core.
    pub code: String,
    pub message: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct CheckResult {
    pub ok: bool,
    pub diagnostics: Vec<Diagnostic>,
}

/// Turn a `catch_unwind` payload into a `Diagnostic`.
///
/// The parser raises a handful of syntax errors via `std::panic::panic_any`
/// instead of the recoverable `push_parse_error` path (`FunctionWithoutType`,
/// `FunctionWithoutReturnType` in `parsing/elements.rs`; a `TypeError::WrongExpression`
/// in `parsing/operation_priority.rs`) — same two call sites `typr-cli`'s
/// `standard_library.rs` already has to work around. `check`/`build` must
/// never let one of these escape as an unhandled panic: unlike the CLI's
/// batch tooling, this runs in a long-lived server process where a crash
/// takes down every in-flight request, not just the offending one.
fn panic_payload_diagnostic(payload: Box<dyn std::any::Any + Send>) -> Diagnostic {
    if let Some(e) = payload.downcast_ref::<SyntaxError>() {
        return Diagnostic {
            code: e.code().to_string(),
            message: e.simple_message(),
        };
    }
    if let Some(e) = payload.downcast_ref::<TypeError>() {
        return Diagnostic {
            code: e.code().to_string(),
            message: e.simple_message(),
        };
    }
    let message = payload
        .downcast_ref::<&str>()
        .map(|s| s.to_string())
        .or_else(|| payload.downcast_ref::<String>().cloned())
        .unwrap_or_else(|| "internal parser error".to_string());
    Diagnostic {
        code: "S000".to_string(),
        message,
    }
}

fn check_source(source: &str) -> CheckResult {
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| check_source_inner(source))) {
        Ok(result) => result,
        Err(payload) => CheckResult {
            ok: false,
            diagnostics: vec![panic_payload_diagnostic(payload)],
        },
    }
}

fn check_source_inner(source: &str) -> CheckResult {
    let parsed = parse_from_string_with_errors(source, "main.ty");
    if parsed.has_errors() {
        let diagnostics = parsed
            .errors
            .into_iter()
            .map(|e| {
                let err = TypRError::syntax_error(e);
                Diagnostic {
                    code: err.code().to_string(),
                    message: err.simple_message(),
                }
            })
            .collect();
        return CheckResult { ok: false, diagnostics };
    }

    // Same Environment::Wasm context typr-wasm's type_check() builds: all
    // modules inlined, no source() calls, nothing read from disk.
    let context = Config::default().set_environment(Environment::Wasm).to_context();
    let type_checker = TypeChecker::new(context).typing_no_panic(&parsed.ast);

    let diagnostics = type_checker
        .get_errors()
        .iter()
        .map(|e| Diagnostic {
            code: e.code().to_string(),
            message: e.simple_message(),
        })
        .collect();

    CheckResult {
        ok: !type_checker.has_errors(),
        diagnostics,
    }
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct BuildResult {
    pub ok: bool,
    /// Generated R code, with the standard library, type annotations, and
    /// generic function dispatchers inlined — produced even when
    /// `diagnostics` is non-empty (best-effort transpilation, same as
    /// `typr-wasm`'s `compile()`).
    pub r_code: String,
    pub diagnostics: Vec<Diagnostic>,
}

fn build_source(source: &str) -> BuildResult {
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| build_source_inner(source))) {
        Ok(result) => result,
        Err(payload) => BuildResult {
            ok: false,
            r_code: String::new(),
            diagnostics: vec![panic_payload_diagnostic(payload)],
        },
    }
}

fn build_source_inner(source: &str) -> BuildResult {
    let parsed = parse_from_string_with_errors(source, "main.ty");
    if parsed.has_errors() {
        let diagnostics = parsed
            .errors
            .into_iter()
            .map(|e| {
                let err = TypRError::syntax_error(e);
                Diagnostic {
                    code: err.code().to_string(),
                    message: err.simple_message(),
                }
            })
            .collect();
        return BuildResult {
            ok: false,
            r_code: String::new(),
            diagnostics,
        };
    }

    // Same Environment::Wasm context check_source() builds.
    let context = Config::default().set_environment(Environment::Wasm).to_context();
    let type_checker = TypeChecker::new(context).typing_no_panic(&parsed.ast);

    let diagnostics: Vec<Diagnostic> = type_checker
        .get_errors()
        .iter()
        .map(|e| Diagnostic {
            code: e.code().to_string(),
            message: e.simple_message(),
        })
        .collect();
    let ok = !type_checker.has_errors();

    // Transpile proceeds even with type errors (best-effort output), mirroring
    // typr-wasm's compile().
    let context = type_checker.get_context();
    let main_code = type_checker.transpile();
    let type_annotations = context.get_type_anotations();
    let generic_functions: String = context
        .get_all_generic_functions()
        .iter()
        .map(|(var, _)| var.get_name())
        .filter(|x| !x.contains("<-"))
        .map(|fn_name| {
            format!(
                "{} <- function(x, ...) UseMethod('{}', x)",
                fn_name,
                fn_name.replace("`", "")
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let mut r_code = String::new();
    r_code.push_str("# === TypR Standard Library ===\n");
    r_code.push_str(STD_R);
    r_code.push_str("\n\n");
    if !generic_functions.trim().is_empty() {
        r_code.push_str("# === Generic Functions ===\n");
        r_code.push_str(&generic_functions);
        r_code.push_str("\n\n");
    }
    if !type_annotations.trim().is_empty() {
        r_code.push_str("# === Type Annotations ===\n");
        r_code.push_str(&type_annotations);
        r_code.push_str("\n\n");
    }
    r_code.push_str("# === Main Code ===\n");
    r_code.push_str(&main_code);

    BuildResult {
        ok,
        r_code,
        diagnostics,
    }
}

#[derive(Debug, Deserialize, JsonSchema)]
pub struct ExplainParams {
    /// Diagnostic code to explain, e.g. "T001" or "S003" — the `code` field
    /// of a `check`/`build` diagnostic.
    pub code: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct ExplainResult {
    pub code: String,
    /// False if `code` isn't covered — practically only the handful of
    /// declared-but-dead codes `check`/`build` can never actually produce
    /// (see `explain::ENTRIES`'s module docs). The other fields are then
    /// absent; fall back to the diagnostic's own `message` from
    /// `check`/`build` in that case.
    pub found: bool,
    pub title: Option<String>,
    pub explanation: Option<String>,
    /// Minimal TypR source that reproduces this diagnostic.
    pub bad_example: Option<String>,
    /// The same source, fixed — type-checks cleanly.
    pub good_example: Option<String>,
}

fn explain_code(code: &str) -> ExplainResult {
    match explain::find(code) {
        Some(e) => ExplainResult {
            code: e.code.to_string(),
            found: true,
            title: Some(e.title.to_string()),
            explanation: Some(e.explanation.to_string()),
            bad_example: Some(e.bad.to_string()),
            good_example: Some(e.good.to_string()),
        },
        None => ExplainResult {
            code: code.to_string(),
            found: false,
            title: None,
            explanation: None,
            bad_example: None,
            good_example: None,
        },
    }
}

#[derive(Debug, Deserialize, JsonSchema)]
pub struct DocsSearchParams {
    /// Free-text query, e.g. "dplyr", "how do I embed a type", "match exhaustive".
    /// Matched case-insensitively, word by word, against each page's title,
    /// category, and description.
    pub query: String,
}

#[derive(Debug, Serialize, JsonSchema, PartialEq, Eq)]
pub struct DocMatch {
    pub title: String,
    /// Diátaxis category: Tutorial, How-To, Reference, Philosophy, or Deep Dive.
    pub category: String,
    pub description: String,
    pub url: String,
}

#[derive(Debug, Serialize, JsonSchema)]
pub struct DocsSearchResult {
    /// Up to 8 pages, best match first. Empty means no page's title,
    /// category or description contains any word of the query — try a
    /// broader or different term, or fall back to `typr://docs-index` to
    /// browse the full table.
    pub matches: Vec<DocMatch>,
}

/// One row of the vendored `docs-index.md` table.
struct DocPage {
    title: String,
    category: String,
    description: String,
    url: String,
}

/// Split a `| a | b | c | d |` table row into its four cells, unescaping the
/// `\|` this table uses for a literal pipe inside a cell (see the generator
/// script noted below). Skips the header and `|---|---|---|---|` separator
/// rows, which have no ordinary characters between the pipes.
fn parse_docs_index() -> Vec<DocPage> {
    DOCS_INDEX_MD
        .lines()
        .filter(|line| line.starts_with('|') && !line.starts_with("|---"))
        .filter_map(|line| {
            let cells: Vec<String> = line
                .trim_matches('|')
                .split('|')
                .map(|cell| cell.trim().replace("\\|", "|"))
                .collect();
            match cells.as_slice() {
                [title, category, description, url] if title != "Title" => Some(DocPage {
                    title: title.clone(),
                    category: category.clone(),
                    description: description.clone(),
                    url: url.clone(),
                }),
                _ => None,
            }
        })
        .collect()
}

/// Score a page against a lowercase, whitespace-split query: 3 points per
/// query word found in the title, 1 point per word found in the category or
/// description. A page with no matching word scores 0 and is dropped.
fn score(page: &DocPage, query_words: &[&str]) -> u32 {
    let title = page.title.to_lowercase();
    let category = page.category.to_lowercase();
    let description = page.description.to_lowercase();
    query_words
        .iter()
        .map(|word| {
            let mut s = 0;
            if title.contains(word) {
                s += 3;
            }
            if category.contains(word) || description.contains(word) {
                s += 1;
            }
            s
        })
        .sum()
}

/// Find pages on `typr.github.io/docs/` relevant to a free-text query, so an
/// agent that hits a question `check`/`build`/`explain` and the other
/// resources can't answer (a tutorial's worth of context, design rationale,
/// a how-to for a specific R package) can redirect the user to the right
/// page instead of guessing or staying silent.
///
/// Regenerate `data/docs-index.md` after editing pages on the docs site:
/// there is no build-time link between the two repos, same as every other
/// vendored snapshot here. The generator is a one-off script (not checked
/// in) that reads each page's `title`/`description` frontmatter — see the
/// crate-level docs for the refresh convention; re-run the same script logic
/// if the docs site's page set changes.
fn search_docs(query: &str) -> DocsSearchResult {
    let query_words: Vec<String> = query.to_lowercase().split_whitespace().map(str::to_string).collect();
    let query_words: Vec<&str> = query_words.iter().map(String::as_str).collect();

    let mut scored: Vec<(u32, DocPage)> = parse_docs_index()
        .into_iter()
        .map(|page| (score(&page, &query_words), page))
        .filter(|(s, _)| *s > 0)
        .collect();
    scored.sort_by(|a, b| b.0.cmp(&a.0));

    let matches = scored
        .into_iter()
        .take(8)
        .map(|(_, page)| DocMatch {
            title: page.title,
            category: page.category,
            description: page.description,
            url: page.url,
        })
        .collect();

    DocsSearchResult { matches }
}

#[derive(Clone, Default)]
pub struct TyprMcpServer;

#[tool_router]
impl TyprMcpServer {
    pub fn new() -> Self {
        Self
    }

    #[tool(description = "Type-check TypR source code in-process (no filesystem, no project \
        directory) and report diagnostics with stable error codes (T0xx for type errors, \
        S0xx for syntax errors).")]
    async fn check(&self, Parameters(CheckParams { source }): Parameters<CheckParams>) -> Json<CheckResult> {
        Json(check_source(&source))
    }

    #[tool(
        description = "Transpile TypR source code to R in-process (no filesystem, no project \
        directory), returning the generated R code — with the standard library, type \
        annotations, and generic function dispatchers inlined — plus any diagnostics found \
        while type-checking (stable T0xx/S0xx codes, same as `check`). `r_code` is produced \
        even when type errors are present, so callers should check `ok`/`diagnostics` before \
        trusting the output."
    )]
    async fn build(&self, Parameters(CheckParams { source }): Parameters<CheckParams>) -> Json<BuildResult> {
        Json(build_source(&source))
    }

    #[tool(description = "Explain a TypR diagnostic code (T0xx/S0xx, from a `check`/`build` \
        diagnostic's `code` field) with a longer description of why the compiler rejects it \
        plus a minimal before/after TypR example. Covers every code the compiler can actually \
        produce — `found: false` means this code is declared but dead (unreachable in the \
        current compiler), so fall back to the short `message` `check`/`build` already returned.")]
    async fn explain(&self, Parameters(ExplainParams { code }): Parameters<ExplainParams>) -> Json<ExplainResult> {
        Json(explain_code(&code))
    }

    #[tool(description = "Search typr.github.io/docs/ by keyword and get back matching pages \
        (title, Diátaxis category, one-line description, URL) — for a question `check`/ \
        `build`/`explain` and the other resources can't answer: a tutorial's worth of context, \
        design rationale, or a how-to for a specific R package (dplyr, Shiny, R6...). Redirect \
        the user to the returned URL (or fetch it, if the client has a web tool) rather than \
        guessing at content this server doesn't have. Empty `matches` means no page's title, \
        category or description contains any word of the query — try a broader term or read \
        `typr://docs-index` for the full table.")]
    async fn docs_search(
        &self,
        Parameters(DocsSearchParams { query }): Parameters<DocsSearchParams>,
    ) -> Json<DocsSearchResult> {
        Json(search_docs(&query))
    }
}

