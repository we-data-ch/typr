//! MCP server exposing the TypR compiler to AI agents.
//!
//! Runs over stdio (wired as the `typr mcp` subcommand — never an
//! `npx`/`sh -c` one-liner, see the crate-level design notes) and offers
//! `check` (type-check only) and `build` (transpile to R) tools, both
//! in-process: no filesystem, no project directory, no `.typr_cache`. They
//! reuse the same inlined-context recipe as `typr-wasm`'s `compile`/
//! `typeCheck` (the browser playground), which is the proof this works
//! without I/O.
//!
//! It also serves two read-only **resources**, `typr://lexicon` and
//! `typr://operators`: the same generated reference tables published at
//! `typr.github.io/docs/reference/{lexicon,operators}.md`, so an agent that
//! hits an unfamiliar sigil or operator in a `check`/`build` diagnostic (say
//! `?B` or `|>`) can look it up without leaving the MCP session or guessing.
//! Kept in-process the same way `STD_R` is: a vendored snapshot
//! (`data/*.md`, `include_str!`'d below), not a live fetch from the docs
//! site. **This snapshot must be refreshed by hand** (`cp` from
//! `typr.github.io/docs/reference/`) whenever those pages are regenerated by
//! `npm run syntax:reference` over there — there is no CI check tying the
//! two repos together yet.
//!
//! A third tool, `explain`, takes a diagnostic `code` (`T0xx`/`S0xx`, as
//! returned by `check`/`build`) and returns a longer explanation plus a
//! minimal before/after example, for every code in [`explain::ENTRIES`] —
//! see that module's docs for the handful of declared-but-dead codes it
//! doesn't (and can't) cover.
//!
//! Type checking is recursive, so a long-lived server must drive it from a
//! large-stack thread — see [`run_stdio`].
//!
//! ## Client configuration
//!
//! Point an MCP client at the `typr` binary with the `mcp` argument. After
//! `cargo install typr`, that's just:
//!
//! ```json
//! {
//!   "mcpServers": {
//!     "typr": {
//!       "command": "typr",
//!       "args": ["mcp"]
//!     }
//!   }
//! }
//! ```
//!
//! Building from a local checkout instead? Point `command` at
//! `target/debug/typr` (or `target/release/typr`).

